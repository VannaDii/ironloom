"""Generate immutable Dart wire records from the shared Rust contract declarations.

Committed Rust schemas cross-check fields. Semantic invariants live in invariants.dart;
shared decode fixtures check the public constructors independently in both languages.
Run from any directory with python3 packages/ironloom_client/tool/generate_models.py.
"""
import json
import pathlib
import re
import subprocess

PACKAGE = pathlib.Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parents[1]
SOURCES = sorted((ROOT / 'crates').glob('*/src/factory.rs'))
records = {}
enums = {}
for path in SOURCES:
    source = path.read_text()
    for name, fields, body in re.findall(
        r'(\w+), \w+Data \{(.*?)\} \|value\| \{(.*?)\n\}', source, re.S
    ):
        fields = re.sub(r'\s*///[^\n]*', '', fields)
        records[name] = (re.findall(r'(\w+): ([^,\n]+),', fields), body)
    for name, body in re.findall(r'pub enum (\w+) \{(.*?)\n\}', source, re.S):
        body = re.sub(r'\s*///[^\n]*', '', body)
        if '(' not in body and '{' not in body:
            enums[name] = re.findall(r'\b(\w+)\s*,', body)

schemas = {}
for path in (ROOT / 'crates').glob('*/schemas/*.schema.json'):
    schema = json.loads(path.read_text())
    schemas.update(schema.get('$defs', {}))
for name, (fields, _) in records.items():
    assert set(dict(fields)) == set(schemas[name + 'Data']['properties']), name

ids = re.findall(r'typed_id!\((\w+),', (ROOT / 'crates/ironloom-core/src/lib.rs').read_text())
ids += ['BranchName', 'RepositorySlug']
def snake(name):
    return re.sub(r'(?<!^)([A-Z])', r'_\1', name).lower()
def camel(name):
    value = re.sub(r'_([a-z])', lambda m: m[1].upper(), name)
    return value + 'Value' if value in {'new', 'class', 'switch', 'default'} else value
def base(typ):
    return typ.split('::')[-1]
def dtype(typ):
    if typ.startswith('Option<'): return dtype(typ[7:-1]) + '?'
    if typ.startswith('Vec<'): return 'List<' + dtype(typ[4:-1]) + '>'
    return {'String': 'String', 'bool': 'bool', 'Value': 'Object?'}.get(base(typ), base(typ))
def decoder(typ):
    if typ.startswith('Vec<'): return '(v) => _list(v, ' + decoder(typ[4:-1]) + ')'
    return {'String': '_string', 'bool': '_boolean', 'Value': '_freeze'}.get(base(typ), base(typ) + '.fromJson')

out = ["// Generated by tool/generate_models.py; edit declarations or invariants, then regenerate.", "part of 'contracts.dart';", '']
for name in ids:
    out += [f'final class {name} implements WireModel {{', f'  factory {name}(String value) => {name}.fromJson(value);', f'  {name}._(this.value);', f'  factory {name}.fromJson(Object? json) {{', '    final value = _string(json);', f'    _validateIdentity({json.dumps(name)}, value);', f'    return {name}._(value);', '  }', '  final String value;', '  @override', '  String toJson() => value;', '  @override', f'  void validate() => _validateIdentity({json.dumps(name)}, value);', '  @override', '  String toString() => value;', '}', '']
for name, values in enums.items():
    out += [f'enum {name} implements WireModel {{']
    out += [f"  {camel(snake(v))}('{snake(v)}'){';' if i == len(values)-1 else ','}" for i,v in enumerate(values)]
    out += [f'  const {name}(this.value);', '  final String value;', f'  static {name} fromJson(Object? json) => values.firstWhere(', '    (v) => v.value == json,', "    orElse: () => _fail(r'$', 'invalid_structure'),", '  );', '  @override', '  String toJson() => value;', '  @override', '  void validate() {}', '}', '']
for name,(fields,body) in records.items():
    out += [f'final class {name} implements WireModel {{', f'  factory {name}({{']
    out += [f"    {'required ' if not typ.startswith('Option<') else ''}{dtype(typ)} {camel(field)}," for field,typ in fields]
    out += [f'  }}) => {name}.fromJson({{']
    out += [f"    '{field}': _json({camel(field)})," for field,_ in fields]
    out += ['  });', f'  {name}._({", ".join("this." + camel(f) for f,_ in fields)});', f'  factory {name}.fromJson(Object? json) {{', f'    final r = _Reader(json, {json.dumps([f for f,_ in fields])});', f'    final value = {name}._(']
    for field,typ in fields:
        optional=typ.startswith('Option<')
        inner=typ[7:-1] if optional else typ
        out += [f"      r.{'optional' if optional else 'read'}('{field}', {decoder(inner)}),"]
    out += ['    );', '    value.validate();', '    return value;', '  }']
    out += [f'  final {dtype(typ)} {camel(field)};' for field,typ in fields]
    out += ['  @override', '  void validate() {']
    # Straight-line required/positive checks preserve Rust ordering. Cross-field checks below.
    prefix = re.split(r'\b(?:if|for)\b', body, maxsplit=1)[0]
    checks = re.findall(r'(positive|required)\("([^\"]+)", (?:&)?value\.([\w.]+)\)', prefix)
    # Complex bodies need ordering hand-written alongside their cross-field checks.
    complex_names={'StorageRoots','ModelSelection','Usage','Resource','WorkerPaths','InferenceRequest','PlanRevision','Residency'}
    if name not in complex_names:
        out += [f"    _{fn}('{field}', {'.'.join(camel(s) for s in access.split('.'))});" for fn,field,access in checks]
    out += ['    _validateModel(this);', '  }', '  @override', '  Map<String, Object?> toJson() => {']
    out += [f"    '{field}': _json({camel(field)})," for field,_ in fields]
    out += ['  };', '}', '']
# Tagged command payload uses the same validated record constructors.
out += ["final class CommandAction implements WireModel {", "  factory CommandAction(String type, WireModel data) => CommandAction.fromJson({'type': type, 'data': data.toJson()});", "  CommandAction._(this.type, this.data);", "  factory CommandAction.fromJson(Object? json) {", "    final r = _Reader(json, ['type', 'data']);", "    final type = r.read('type', _string);", "    final decoder = switch(type) {"]
for key,name in [('input','InputCommand'),('steer','SteeringInput'),('answer','QuestionAnswer'),('approve','ApprovalCommand'),('control','ControlCommand'),('budget','Budget'),('lesson','LessonMutation')]:
    out += [f"      '{key}' => {name}.fromJson,"]
out += ["      _ => _fail('type', 'invalid_structure'),", '    };', "    return CommandAction._(type, r.read('data', decoder));", '  }', '  final String type;', '  final WireModel data;', '  @override', '  void validate() => data.validate();', '  @override', "  Map<String, Object?> toJson() => {'type': type, 'data': data.toJson()};", '}']
(PACKAGE / 'lib/src/models.g.dart').write_text('\n'.join(out) + '\n')
print(f'Generated {len(records)} records, {len(ids)} identities, {len(enums)} enums; schema fields match.')

subprocess.run(['dart', 'format', str(PACKAGE / 'lib/src/models.g.dart')], check=True)
